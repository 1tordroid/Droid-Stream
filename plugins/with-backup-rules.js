const fs = require('fs');
const path = require('path');
const {
  withAndroidManifest,
  withDangerousMod,
} = require('expo/config-plugins');
// The library's own alias helper, so the key file names always match what it
// writes on the phone. This file has no imports, so it loads in Node.
const {stringToHex} = require('react-native-mmkv-storage/dist/src/utils');

// Every MMKV instance opened with withEncryption(). Keep this list in sync
// with SECURE_STORE_IDS in src/lib/storage/secureStores.ts; a Jest test checks
// both against the source.
const ENCRYPTED_INSTANCE_IDS = [
  'droid-stream-sources',
  'droid-stream-debrid',
  'droid-stream-watch-sync',
  'droid-stream-stremio',
  'droid-stream-torrents',
  'provider-source-tokens',
  'droid-stream-jiotv',
  'droid-stream-profiles',
  'droid-stream-ftp',
];

// The library's index of instances (id, encrypted, alias). It holds no user
// data. It must not be restored: when it says an instance is encrypted, the
// library loads the old key, finds none and the store stays unusable
// (initializer.js: IDStore.exists -> initWithEncryptionUsingOldKey). Without
// it, encrypted stores start empty with a new key, and unencrypted stores
// open their restored files as before.
const MMKV_ID_STORE = 'mmkvIDStore';

// Unencrypted stores that stay on the phone: the network library's scans
// and title matches (src/lib/netlib/cache.ts) are rebuilt by a rescan.
const LOCAL_ONLY_INSTANCE_IDS = ['netlib'];

const BACKUP_RULES = 'droid_stream_backup_rules';
const DATA_EXTRACTION_RULES = 'droid_stream_data_extraction_rules';

/** Keystore alias the library uses for an instance's key (mmkvloader.js). */
const keyAlias = instanceId => stringToHex(`com.MMKV.${instanceId}`);

/**
 * Paths under getFilesDir() that must not leave the phone. The Android
 * Keystore key that wraps each instance key is never backed up, so the MMKV
 * file and its wrapped key files are useless, and harmful, on a restore.
 */
const excludedPaths = (ids = ENCRYPTED_INSTANCE_IDS) => [
  ...ids.flatMap(id => {
    const alias = keyAlias(id);
    return [
      `mmkv/${id}`,
      `mmkv/${id}.crc`,
      `SKS_KEY_FILE${alias}`,
      `SKS_DATA_FILE${alias}`,
    ];
  }),
  ...LOCAL_ONLY_INSTANCE_IDS.flatMap(id => [`mmkv/${id}`, `mmkv/${id}.crc`]),
  `mmkv/${MMKV_ID_STORE}`,
  `mmkv/${MMKV_ID_STORE}.crc`,
];

const excludeLines = (paths, indent) =>
  paths
    .map(item => `${indent}<exclude domain="file" path="${item}" />`)
    .join('\n');

/** Android 11 and lower: android:fullBackupContent. */
const buildBackupRulesXml = (paths = excludedPaths()) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-backup-rules.js. Everything else is backed up. -->
<full-backup-content>
${excludeLines(paths, '  ')}
</full-backup-content>
`;

/** Android 12 and higher: android:dataExtractionRules. */
const buildDataExtractionRulesXml = (paths = excludedPaths()) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-backup-rules.js. Everything else is backed up. -->
<data-extraction-rules>
  <cloud-backup>
${excludeLines(paths, '    ')}
  </cloud-backup>
  <device-transfer>
${excludeLines(paths, '    ')}
  </device-transfer>
</data-extraction-rules>
`;

/** Points <application> at the two rule files. */
const setBackupRuleAttributes = manifest => {
  const application = manifest.manifest?.application?.[0];
  if (!application) {
    throw new Error('with-backup-rules: AndroidManifest.xml has no <application>');
  }
  application.$ = application.$ || {};
  application.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
  application.$['android:dataExtractionRules'] = `@xml/${DATA_EXTRACTION_RULES}`;
  return manifest;
};

const writeRuleFiles = projectRoot => {
  const xmlDir = path.join(projectRoot, 'android', 'app', 'src', 'main', 'res', 'xml');
  fs.mkdirSync(xmlDir, {recursive: true});
  fs.writeFileSync(path.join(xmlDir, `${BACKUP_RULES}.xml`), buildBackupRulesXml(), 'utf8');
  fs.writeFileSync(
    path.join(xmlDir, `${DATA_EXTRACTION_RULES}.xml`),
    buildDataExtractionRulesXml(),
    'utf8',
  );
};

/**
 * Keeps the encrypted sign-in stores out of Auto Backup and device transfer.
 * Settings in unencrypted stores are still backed up.
 */
const withBackupRules = config => {
  config = withAndroidManifest(config, manifestConfig => {
    setBackupRuleAttributes(manifestConfig.modResults);
    return manifestConfig;
  });
  return withDangerousMod(config, [
    'android',
    async cfg => {
      writeRuleFiles(cfg.modRequest.projectRoot);
      return cfg;
    },
  ]);
};

module.exports = withBackupRules;
module.exports.ENCRYPTED_INSTANCE_IDS = ENCRYPTED_INSTANCE_IDS;
module.exports.LOCAL_ONLY_INSTANCE_IDS = LOCAL_ONLY_INSTANCE_IDS;
module.exports.keyAlias = keyAlias;
module.exports.excludedPaths = excludedPaths;
module.exports.buildBackupRulesXml = buildBackupRulesXml;
module.exports.buildDataExtractionRulesXml = buildDataExtractionRulesXml;
module.exports.setBackupRuleAttributes = setBackupRuleAttributes;
module.exports.writeRuleFiles = writeRuleFiles;
